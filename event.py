import logging
import uuid
from datetime import datetime, timedelta

from trytond.model import Check, ModelSQL, ModelView, Unique, fields
from trytond.pool import Pool
from trytond.pyson import Eval
from trytond.transaction import without_check_access

logger = logging.getLogger(__name__)

# Which fields apply to each kind of event.
PERSON_TYPES = ['person_motion', 'person_detection']
# Camera and detection-service status changes, recorded as events (not alarms).
STATUS_TYPES = ['camera_offline', 'camera_online', 'service_down', 'service_up']
# Status events about the service as a whole do not belong to a camera.
SERVICE_TYPES = ['service_down', 'service_up']
PERSON = {'invisible': ~Eval('type').in_(PERSON_TYPES)}
MOVEMENT = {'invisible': Eval('type') != 'camera_movement'}
SNAPSHOT = {'invisible': Eval('type') == 'camera_movement'}

# The title of the notice (and of the status events) of each kind.
TITLES = {
    'person_motion': 'Movimiento de persona',
    'person_detection': 'Persona detectada',
    'camera_offline': 'Cámara sin conexión',
    'camera_online': 'Cámara recuperada',
    'service_down': 'Servicio de detección sin señal',
    'service_up': 'Servicio de detección recuperado',
    }


class Event(ModelSQL, ModelView):
    "Esdeveniment de videovigilància"
    __name__ = 'videovigilance.event'

    uid = fields.Char(
        "Identifier", required=True, readonly=True,
        help="Unique identifier generated by the detection service; avoids duplicates on retries.")
    camera = fields.Many2One(
        'videovigilance.camera', "Camera", readonly=True, ondelete='RESTRICT',
        states={'required': ~Eval('type').in_(SERVICE_TYPES)})
    type = fields.Selection(
        [('person_motion', "Person Motion"),
            ('person_detection', "Person Detection"),
            ('camera_movement', "Camera Movement"),
            ('camera_offline', "Camera Offline"),
            ('camera_online', "Camera Recovered"),
            ('service_down', "Detection Service Silent"),
            ('service_up', "Detection Service Recovered")],
        "Type", required=True, readonly=True)
    started_at = fields.DateTime("Start", required=True, readonly=True)
    ended_at = fields.DateTime(
        "End", readonly=True,
        help="Empty while the camera is still moving.")
    max_persons = fields.Integer(
        "Maximum Persons", readonly=True, states=PERSON,
        domain=[('max_persons', '>=', 0)])
    max_confidence = fields.Float(
        "Maximum Confidence", readonly=True, states=PERSON,
        domain=[('max_confidence', '>=', 0), ('max_confidence', '<=', 1)])
    snapshot = fields.Binary(
        "Snapshot", readonly=True, states=SNAPSHOT,
        file_id='snapshot_id', store_prefix='videovigilance',
        help="Detection picture, or the last picture of the camera for a status change.")
    snapshot_id = fields.Char("File ID", readonly=True)
    message = fields.Char(
        "Message", readonly=True, states={'invisible': ~Eval('type').in_(STATUS_TYPES)})
    user = fields.Many2One(
        'res.user', "User", readonly=True, ondelete='SET NULL', states=MOVEMENT,
        help="Who moved the camera.")
    directions = fields.Char(
        "Directions", readonly=True, states=MOVEMENT,
        help="Where the camera moved to, in the order it happened.")
    last_command_at = fields.DateTime("Last Command", readonly=True)
    start_frame = fields.Binary(
        "Start Image", readonly=True, states=MOVEMENT,
        file_id='start_frame_id', store_prefix='videovigilance',
        help="Image just before it started to move (only if someone was watching the live video).")
    start_frame_id = fields.Char("Start File ID", readonly=True)
    end_frame = fields.Binary(
        "End Image", readonly=True, states=MOVEMENT,
        file_id='end_frame_id', store_prefix='videovigilance')
    end_frame_id = fields.Char("End File ID", readonly=True)

    @classmethod
    def __setup__(cls):
        super().__setup__()
        table = cls.__table__()
        cls._sql_constraints += [
            ('uid_unique', Unique(table, table.uid),
                'videovigilance.msg_event_uid_unique'),
            ('period_valid', Check(table, table.ended_at >= table.started_at),
                'videovigilance.msg_event_period_invalid'),
            ]
        cls._order = [('started_at', 'DESC'), ('id', 'DESC')]

    @classmethod
    def create(cls, vlist):
        events = super().create(vlist)
        try:
            cls.notify(events)
        except Exception:
            # A notification failure must never prevent the event from being recorded.
            logger.exception("No s'han pogut enviar els avisos dels esdeveniments")
        return events

    @classmethod
    def create_once(cls, values):
        "Create the event of `values` unless one with its uid exists: (event, created)."
        events = cls.search([('uid', '=', values['uid'])], limit=1)
        if events:
            return events[0], False
        event, = cls.create([values])
        return event, True

    @classmethod
    def record_status(cls, notices):
        """Record one event per camera or service status notice, in the same order.

        A notice about a camera keeps its latest frame: the last picture before it went
        dark, which the camera replaces once it is back.
        """
        now = datetime.now()
        with without_check_access():
            Camera = Pool().get('videovigilance.camera')
            return cls.create([{
                        'uid': uuid.uuid4().hex, 'type': notice['type'],
                        'camera': notice.get('camera'), 'started_at': now,
                        'message': notice['body'],
                        'snapshot': Camera(notice['camera']).frame
                        if notice.get('camera') else None,
                        } for notice in notices])

    @classmethod
    def notify(cls, events):
        from .push import local_time, notify_users
        # Only people raise alarms; camera movements are just recorded.
        events = [event for event in events if event.type in PERSON_TYPES]
        if not events:
            return
        Configuration = Pool().get('videovigilance.configuration')
        if not Configuration.is_armed():
            return
        with without_check_access():
            configuration = Configuration.get_singleton()
            quiet = timedelta(seconds=(
                    configuration.ptz_quiet_seconds if configuration is not None
                    else Configuration.default_ptz_quiet_seconds()))
            now = datetime.now()
            # Moving the camera shifts the whole scene, which looks like motion; a
            # person in view is still a person, so only motion is muted.
            events = [event for event in events
                if event.type == 'person_detection'
                or not (event.camera.ptz_moved_at
                    and now - event.camera.ptz_moved_at < quiet)]
            if not events:
                return
            notify_users([{
                        'body': '%s · %s · %d persona(s)' % (
                            event.camera.name, local_time(event.started_at),
                            event.max_persons or 1),
                        'event': event.id,
                        'camera': event.camera.id,
                        'type': event.type,
                        } for event in events])
